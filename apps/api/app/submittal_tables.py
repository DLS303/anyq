"""SQL tables for material approvals.

Kept off the store metadata. Revision 0009 creates them with op.create_table.
"""

from __future__ import annotations

from sqlalchemy import Column, Float, Index, Integer, MetaData, String, Table, Text, text

metadata = MetaData()

material_approvals = Table(
    "material_approvals",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("company_id", String(180), nullable=False),
    Column("project_id", String(80), nullable=False),
    Column("root_id", String(36), nullable=False),
    Column("parent_id", String(36)),
    Column("number", String(32), nullable=False),
    Column("request_item_id", String(80)),
    Column("name", String(200), nullable=False),
    Column("brand", String(200), nullable=False),
    Column("manufacturer", String(200)),
    Column("unit", String(40), nullable=False),
    Column("qty", Float, nullable=False),
    Column("need_by", String(10)),
    Column("status", String(32), nullable=False),
    Column("version", Integer, nullable=False),
    Column("indicative_price", Float),
    Column("price_file_id", String(36)),
    Column("author_id", String(80), nullable=False),
    Column("comment", Text),
    Column("created_by", String(80), nullable=False),
    Column("updated_by", String(80), nullable=False),
    Column("created_at", String(40), nullable=False),
    Column("updated_at", String(40), nullable=False),
    Column("row_version", Integer, nullable=False),
    Column("deleted_at", String(40)),
    Index("uq_material_approvals_project_number", "project_id", "number", unique=True),
    Index("ix_material_approvals_company_updated", "company_id", "updated_at"),
    Index("ix_material_approvals_root", "root_id"),
    Index(
        "ix_material_approvals_project_status_due",
        "project_id",
        "status",
        "need_by",
        sqlite_where=text("deleted_at IS NULL"),
        postgresql_where=text("deleted_at IS NULL"),
    ),
)

